"""Generates the WIKI-subset benchmark dataset checked into ``data/``.

Uni-Detect's own evaluation corpus (paper Section 4.1) is **WIKI**: "a subset
of WEB from the wikipedia.org domain with over 3M tables." Shipping (or
downloading, in CI, on every run) anything close to that scale is neither
practical nor reproducible for a small, fast, version-over-version regression
benchmark, so this script instead materializes a small, deterministic set of
tables that follow the same shapes Wikipedia's own list-article and infobox
tables take -- code/ID columns, key -> label mappings, population/vote-share
figures, and person/place name columns -- with real-world values (ISO 3166
country codes and names, well-known surnames, ...) rather than arbitrary
synthetic strings.

Two things this generator deliberately keeps separate, after an earlier
version of this file conflated them (see git history / PR discussion if you
are looking for the "why"):

1. **The background corpus** (``build_corpus``) is generated from wide,
   principled parameter ranges that do not reference any specific
   evaluation target. A corpus whose row-counts/spread/domain-width are
   reverse-engineered to match a handful of known eval targets' feature
   buckets is not a fair test of anything -- it just guarantees the answer
   key is right, the same way training on the test set guarantees high
   accuracy. This corpus should be plausible "what a chunk of Wikipedia
   looks like" background data on its own, independent of what gets
   evaluated against it.

2. **The evaluation targets** (``build_eval_targets``) are generated by
   programmatically injecting errors into clean base tables at three
   *severity* levels (``subtle``, ``moderate``, ``obvious``), each repeated
   across multiple random seeds, plus multiple false-positive shapes per
   error type (including the paper's own canonical false-positive examples,
   which are hard-to-get-right *by design*). This does two things a single
   fixed true-positive/false-positive pair per error type cannot: it gives
   enough targets (~15 per error type, ~60 total, vs. the previous 2/8) for
   precision/recall/F1 to be a meaningful fraction instead of a coin flip,
   and it lets ``run_benchmark.py`` report accuracy *by severity* -- i.e.
   answer "how does detection hold up as the data gets dirtier" instead of
   reporting one binary pass/fail per error type.

Network access is deliberately not used: the values below are hand-curated
from well-known, mostly-static reference facts (ISO country codes/names,
common English surnames, ...) so the generated dataset is fully reproducible
offline and in CI. Run this script to regenerate ``data/`` after changing
anything below:

    uv run python benchmarks/wiki_subset/generate_dataset.py
"""

