def _fixed_distance_pair(rnd: random.Random, distance: int, length: int = 9) -> tuple[str, str]:
    """Two same-length strings whose Levenshtein distance is exactly ``distance``.

    Starts from a fixed base string and substitutes ``distance`` distinct
    positions with a character guaranteed to differ from the original --
    substitution is the cheapest edit, so this is exactly ``distance`` apart,
    not just "close to" it.
    """
    base = "abcdefghijklmnopqrstuvwxyz"[:length]
    positions = rnd.sample(range(length), min(distance, length))
    chars = list(base)
    for pos in positions:
        chars[pos] = "z" if base[pos] != "z" else "y"
    return base, "".join(chars)


def _write_csv(path: Path, header: list[str], rows: list[tuple]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(header)
        writer.writerows(rows)


def _clear_dir(path: Path) -> None:
    if path.exists():
        for child in path.rglob("*"):
            if child.is_file():
                child.unlink()
    path.mkdir(parents=True, exist_ok=True)


# ---------------------------------------------------------------------------
# Corpus (background) tables -- one small CSV per Wikipedia-shaped table.
#
# Every range below is chosen to be a plausible, wide spread of "what this
# shape of Wikipedia table looks like in general" -- none of it is fit to
# any specific evaluation target (see module docstring). It is fine, and
# expected, that some eval targets end up in sparsely-covered feature
# buckets: that is a real property of a finite background corpus, not a
# generation bug to paper over.
# ---------------------------------------------------------------------------


def build_corpus() -> None:
    # uniqueness / false-positive baseline: common surnames, natural collisions.
    rnd = random.Random("wiki-uniqueness-names")
    for t in range(15):
        n = rnd.randint(40, 260)
        rows = [(rnd.choice(COMMON_SURNAMES),) for _ in range(n)]
        _write_csv(
            CORPUS_DIR / "uniqueness" / f"notable_people_by_surname_{t:02d}.csv",
            ["surname"],
            rows,
        )

    # uniqueness / true-positive baseline: ID-like codes, always unique.
    # Each value pairs a code with a distinct numeric suffix, which makes the
    # column MIXED_ALPHANUMERIC -- the typical shape of a Wikipedia
    # infobox/list "code" column. Row counts are a deterministic, stratified
    # sweep across every row_count_edges bucket (rather than a pure random
    # draw) so small "Figure-6-style" tables of a handful of rows are
    # guaranteed corpus support, not left to chance.
    rnd = random.Random("wiki-uniqueness-codes")
    code_pool = ISO_CODES + IATA_CODES
    row_count_targets = [6, 12, 20, 30, 45, 70, 100, 150, 220, 300, 380, 420]
    for t, target_n in enumerate(row_count_targets * 2):
        n = max(6, target_n + rnd.randint(-2, 2))
        rows = [(f"{code_pool[i % len(code_pool)]}{(t * 1000 + i):04d}",) for i in range(n)]
        rnd.shuffle(rows)
        _write_csv(
            CORPUS_DIR / "uniqueness" / f"code_list_{t:02d}.csv",
            ["code"],
            rows,
        )

    # numeric_outlier / false-positive baseline: election vote-share percentages.
    rnd = random.Random("wiki-outlier-votes")
    for t in range(24):
        n = rnd.randint(6, 44)
        values = [round(rnd.uniform(0.1, 3.0), 2) for _ in range(n)]
        values[0] = round(rnd.uniform(15, 58), 2)  # legitimate winning candidate, varying margin
        rows = [(v,) for v in values]
        _write_csv(
            CORPUS_DIR / "numeric_outlier" / f"election_result_{t:02d}.csv",
            ["vote_share_pct"],
            rows,
        )

    # numeric_outlier / true-positive baseline: clustered population-ish figures.
    # A wide sweep of both scale (base) and spread, independent of any
    # specific eval target, so the corpus has broad natural coverage of
    # "how clustered do real population-style numeric columns tend to be".
    rnd = random.Random("wiki-outlier-population")
    for t in range(48):
        n = rnd.randint(6, 24)
        base = rnd.uniform(500, 50_000)
        spread = base * rnd.uniform(0.02, 0.35)
        values = [round(base + rnd.uniform(-spread, spread), 1) for _ in range(n)]
        rows = [(v,) for v in values]
        _write_csv(
            CORPUS_DIR / "numeric_outlier" / f"population_thousands_{t:02d}.csv",
            ["population_thousands"],
            rows,
        )

    # spelling / false-positive baseline: short, syntactically-close suffixes.
    rnd = random.Random("wiki-spelling-amendments")
    for t in range(18):
        n = rnd.randint(5, len(ROMAN_NUMERALS))
        values = [f"Amendment {r}" for r in rnd.sample(ROMAN_NUMERALS, n)]
        rows = [(v,) for v in values]
        _write_csv(
            CORPUS_DIR / "spelling" / f"amendment_list_{t:02d}.csv",
            ["title"],
            rows,
        )

    # spelling / true-positive baseline: long, mutually-distinct biography names.
    # A broad, independent sweep over both table size and the differing-token
    # -length dimension the spelling featurization keys on.
    rnd = random.Random("wiki-spelling-names")
    for t in range(30):
        n = rnd.randint(6, len(LONG_NAMES_POOL))
        k = rnd.randint(1, 9)
        word_a = "abcdefghi"[:9]
        word_b = word_a[: 9 - k] + "z" * k
        values = rnd.sample(LONG_NAMES_POOL, max(n - 2, 4)) + [
            f"Biography subject {word_a}",
            f"Biography subject {word_b}",
        ]
        rows = [(v,) for v in values]
        _write_csv(
            CORPUS_DIR / "spelling" / f"biography_list_{t:02d}.csv",
            ["name"],
            rows,
        )

    # functional_dependency / true-positive baseline: near-perfect key -> label.
    rnd = random.Random("wiki-fd-codes")
    for t in range(24):
        n = rnd.randint(30, 340)
        codes = [ISO_CODES[i % len(ISO_CODES)] for i in range(n)]
        rows = [(c, ISO_COUNTRIES[c]) for c in codes]
        _write_csv(
            CORPUS_DIR / "functional_dependency" / f"country_code_table_{t:02d}.csv",
            ["iso_code", "country_name"],
            rows,
        )

    # functional_dependency / false-positive baseline: unrelated small-integer
    # pairs (e.g. a weekly page-view count vs. an unrelated weekly edit
    # count -- plausible Wikipedia analytics columns with no real dependency
    # between them). Domain width varies across tables so both "mostly
    # coincidentally compliant" and "mostly not" corpus shapes exist.
    rnd = random.Random("wiki-fd-unrelated")
    for t in range(28):
        n = rnd.randint(50, 180)
        domain = rnd.randint(80, 700)
        rows = [(str(rnd.randint(0, domain)), str(rnd.randint(0, domain))) for _ in range(n)]
        _write_csv(
            CORPUS_DIR / "functional_dependency" / f"pageviews_vs_edits_{t:02d}.csv",
            ["page_views", "edit_count"],
            rows,
        )


# ---------------------------------------------------------------------------
# Evaluation targets: labeled true-positive / false-positive tables, built by
# programmatically injecting errors into clean base tables at graded
# severity levels. Every target records `severity` (one of SEVERITIES,
# "paper_example", or "clean" for a false positive) so run_benchmark.py can
# report accuracy broken down by how dirty the data actually is.
# ---------------------------------------------------------------------------


def _target(
    *,
    id_: str,
    error_type: str,
    expected_significant: bool,
    severity: str,
    description: str,
    columns: list[str],
    rows: list[list],
) -> dict:
    return {
        "id": id_,
        "error_type": error_type,
        "expected_significant": expected_significant,
        "severity": severity,
        "description": description,
        "columns": columns,
        "rows": rows,
    }


# --- uniqueness --------------------------------------------------------


def _uniqueness_tp(rnd: random.Random, severity: str) -> list[str]:
    n = rnd.randint(110, 180)
    code_pool = ISO_CODES + IATA_CODES
    values = [f"{code_pool[i % len(code_pool)]}{i:04d}" for i in range(n)]
    rnd.shuffle(values)
    # Number of injected duplicate pairs scales with severity; epsilon=0.05
    # on this benchmark's config caps how many rows a single perturbation
    # can drop, so "obvious" deliberately exceeds that budget to exercise
    # the epsilon-budget behavior described in paper Definition 2, not just
    # the easy single-duplicate case.
    n_dupes = {"subtle": 1, "moderate": 4, "obvious": 10}[severity]
    for _ in range(n_dupes):
        i, j = rnd.sample(range(len(values)), 2)
        values[j] = values[i]
    return values


def _uniqueness_fp_variants() -> list[dict]:
    variants = []
    # Paper's own worked example shape (Figure 2(a)/2(b)): a large list of
    # common names/codes with exactly one coincidental duplicate.
    fp_values = (COMMON_SURNAMES[:5] * 20) + [COMMON_SURNAMES[0]]
    variants.append(
        _target(
            id_="uniqueness_fp_common_surnames",
            error_type="uniqueness",
            expected_significant=False,
            severity="paper_example",
            description=(
                "Paper Figure 2(a)-style: a 'List of notable people named Smith' table "
                "with one coincidental duplicate surname among common names."
            ),
            columns=["surname"],
            rows=[[v] for v in fp_values],
        )
    )
    # Additional natural-collision variants across different pool widths --
    # a narrower pool of surnames makes coincidental duplicates *more*
    # common, the harder (more adversarial) end of this false-positive shape.
    rnd = random.Random("wiki-eval-uniqueness-fp")
    for i, pool_size in enumerate((4, 6, 8, 10)):
        n = rnd.randint(80, 160)
        pool = COMMON_SURNAMES[:pool_size]
        values = [rnd.choice(pool) for _ in range(n)]
        variants.append(
            _target(
                id_=f"uniqueness_fp_surname_pool{pool_size}_{i:02d}",
                error_type="uniqueness",
                expected_significant=False,
                severity="clean",
                description=(
                    f"A 'notable people' list drawn from only {pool_size} common surnames "
                    "-- natural collisions expected, not a data error."
                ),
                columns=["surname"],
                rows=[[v] for v in values],
            )
        )
    return variants


def build_uniqueness_targets() -> list[dict]:
    targets: list[dict] = list(_uniqueness_fp_variants())
    # Paper Figure 6's own real uniqueness violation: a "Part No." column
    # with 6 mostly-unique alphanumeric codes and one exact duplicate
    # ("KV214-310B8K2" appearing twice).
    part_no_values = [
        "KV214-310B8K2",
        "MP2492DN",
        "B32671L1272J",
        "MFI341S2500",
        "KV214-310B8K2",
        "P1087",
    ]
    targets.append(
        _target(
            id_="uniqueness_tp_part_number_paper_example",
            error_type="uniqueness",
            expected_significant=True,
            severity="paper_example",
            description=(
                "Paper Figure 6-style: a 'Part No.' column with one exact duplicate "
                "alphanumeric code -- codes like this are expected to always be unique."
            ),
            columns=["code"],
            rows=[[v] for v in part_no_values],
        )
    )
    for severity in SEVERITIES:
        for i in range(SEEDS_PER_CELL):
            rnd = random.Random(f"wiki-eval-uniqueness-tp-{severity}-{i}")
            values = _uniqueness_tp(rnd, severity)
            targets.append(
                _target(
                    id_=f"uniqueness_tp_{severity}_{i:02d}",
                    error_type="uniqueness",
                    expected_significant=True,
                    severity=severity,
                    description=(
                        f"An airport/ISO-code-style ID column ({severity} corruption: "
                        f"{ {'subtle': 1, 'moderate': 4, 'obvious': 10}[severity] } injected "
                        "duplicate(s)) -- codes like this are expected to always be unique."
                    ),
                    columns=["code"],
                    rows=[[v] for v in values],
                )
            )
    return targets


# --- numeric_outlier -----------------------------------------------------


def _outlier_tp(rnd: random.Random, severity: str) -> list[float]:
    n = rnd.randint(6, 9)
    base = rnd.uniform(8000, 14000)
    spread = base * 0.06
    values = [round(base + rnd.uniform(-spread, spread), 1) for _ in range(n)]
    # A "missing/misplaced decimal point" error, the paper's own motivating
    # example -- severity is how many digits the point is off by.
    divisor = {"subtle": 10.0, "moderate": 100.0, "obvious": 1000.0}[severity]
    idx = rnd.randrange(len(values))
    values[idx] = round(values[idx] / divisor, 3)
    return values


